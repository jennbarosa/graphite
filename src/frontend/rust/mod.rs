//! Rust output. Each graph becomes one module, `<graph>.rs`, holding its tables as `static` data
//! and a constant for each node, condition and choice. Every module imports the runtime types from
//! `graphite.rs`, so the host crate declares `mod graphite;` next to the generated modules.

use std::collections::HashSet;
use std::io::{self, Write};
use std::path::{Path, PathBuf};
use std::process::Command;

use super::{Frontend, Module};
use crate::frontend::registry::{Debugger, Target};
use crate::graph::{Annotation, CompiledGraph, Span, index};
use crate::interner::StringId;

/// File name of the runtime module. Every graph module imports it as `crate::graphite`.
pub const RUNTIME_FILE: &str = "graphite.rs";

const RUNTIME: &str = include_str!("runtime.rs");

pub struct Rust;

pub const RUST: Rust = Rust;

pub const TARGET: Target = Target {
    key: "rust",
    frontend: &RUST,
    debugger: Some(Debugger::Program(build_debugger)),
    runtime: None,
};

/// The debugger's entry point, written beside the graph's modules, and the program it builds.
const DEBUGGER_MAIN: &str = "graphite_debugger.rs";
const DEBUGGER_PROGRAM: &str = "graphite_debugger";

/// Builds the debugger for graph `stem`: a program with the runtime and the graph's module,
/// compiled with `rustc` in `directory`. The runtime and the module must already be there.
pub fn build_debugger(directory: &Path, stem: &str) -> Result<PathBuf, String> {
    // The stem goes into Rust source below, so it must be a module name first.
    if !is_module_name(stem) {
        return Err(format!("graph `{stem}` cannot be a Rust module"));
    }
    let main = directory.join(DEBUGGER_MAIN);
    let source = format!(
        "mod graphite;\nmod {stem};\n\nfn main() {{\n    graphite::debug(&{stem}::GRAPH).expect(\"debugger I/O\");\n}}\n"
    );
    let program = directory.join(format!(
        "{DEBUGGER_PROGRAM}{}",
        std::env::consts::EXE_SUFFIX
    ));
    // Refuse to replace a file the user keeps in the directory. `create_new` makes the check and
    // the write one step.
    if program.exists() {
        return Err(format!(
            "{} already exists; pass another --out",
            program.display()
        ));
    }
    let mut file = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&main)
        .map_err(|error| format!("cannot write {}: {error}", main.display()))?;
    std::io::Write::write_all(&mut file, source.as_bytes())
        .map_err(|error| format!("cannot write {}: {error}", main.display()))?;
    let status = Command::new("rustc")
        .args(["--edition", "2021"])
        .arg(&main)
        .arg("-o")
        .arg(&program)
        .status();
    if matches!(&status, Ok(status) if status.success()) {
        return Ok(program);
    }
    // A failed build leaves no half-written entry point behind.
    let _ = std::fs::remove_file(&main);
    match status {
        Ok(status) => Err(format!("rustc could not build the debugger ({status})")),
        Err(error) => Err(format!("cannot run rustc to build the debugger: {error}")),
    }
}

impl Frontend for Rust {
    fn modules(&self, _: &CompiledGraph) -> Vec<Module> {
        vec![Module::Index]
    }

    fn file_name(&self, graph: &CompiledGraph, _: Module) -> String {
        format!("{}.rs", graph.text(graph.name))
    }

    fn emit_module(
        &self,
        graph: &CompiledGraph,
        _: Module,
        output: &mut dyn Write,
    ) -> io::Result<()> {
        let name = graph.text(graph.name);
        if !is_module_name(name) {
            return Err(io::Error::new(
                io::ErrorKind::InvalidData,
                format!(
                    "graph `{name}` cannot be a Rust module: use letters, digits and `_`, do not start with a digit, and avoid Rust keywords"
                ),
            ));
        }
        write_graph(graph, output)
    }

    fn emit_runtime(&self, output: &mut dyn Write) -> io::Result<()> {
        output.write_all(RUNTIME.as_bytes())
    }

    fn runtime_file_name(&self) -> &'static str {
        RUNTIME_FILE
    }
}

/// The whole module: a header, the name constants, then the `GRAPH` table.
fn write_graph(graph: &CompiledGraph, output: &mut dyn Write) -> io::Result<()> {
    write_header(graph, output)?;
    write_constants(graph, output)?;
    writeln!(output, "pub static GRAPH: Graph = Graph {{")?;
    writeln!(output, "    name: {},", quote(graph.text(graph.name)))?;
    write_nodes(graph, output)?;
    writeln!(
        output,
        "    conditions: &[{}],",
        string_list(graph, &graph.conditions)
    )?;
    write_choices(graph, output)?;
    writeln!(output, "}};")
}

fn write_header(graph: &CompiledGraph, output: &mut dyn Write) -> io::Result<()> {
    writeln!(
        output,
        "// Generated by graphite from `{}`. Do not edit.",
        graph.text(graph.name)
    )?;
    writeln!(output, "#![allow(dead_code, unused_imports)]\n")?;
    writeln!(
        output,
        "use crate::graphite::{{Annotation, Arm, Choice, Edge, Graph, Node, NodeId}};\n"
    )
}

/// One `pub mod` per kind of name. Each constant is the name's index in its table.
fn write_constants(graph: &CompiledGraph, output: &mut dyn Write) -> io::Result<()> {
    let nodes = graph
        .nodes
        .iter()
        .enumerate()
        .map(|(id, node)| (graph.text(node.name), format!("super::NodeId({id})")));
    constants(output, "nodes", "super::NodeId", nodes)?;

    let conditions = graph
        .conditions
        .iter()
        .enumerate()
        .map(|(id, name)| (graph.text(*name), id.to_string()));
    constants(output, "conditions", "u32", conditions)?;

    let choices = graph
        .choices
        .iter()
        .enumerate()
        .map(|(id, choice)| (graph.text(choice.name), id.to_string()));
    constants(output, "choices", "u32", choices)
}

fn write_nodes(graph: &CompiledGraph, output: &mut dyn Write) -> io::Result<()> {
    writeln!(output, "    nodes: &[")?;
    for node in &graph.nodes {
        write!(
            output,
            "    Node {{ name: {}, offset: {}, looping: {}, end: {}, sequence: {}, flags: &[{}], annotations: {}, edges: &[",
            quote(graph.text(node.name)),
            node.offset,
            node.looping,
            node.end,
            option(node.sequence),
            string_list(graph, &graph.flags[index(&node.flags)]),
            annotation_list(graph, &node.annotations),
        )?;
        for &edge_id in &graph.outgoing[index(&node.outgoing)] {
            let edge = &graph.edges[edge_id as usize];
            write!(
                output,
                "Edge {{ id: {edge_id}, target: NodeId({}), condition: {}, annotations: {} }}, ",
                edge.target,
                option(edge.condition),
                annotation_list(graph, &edge.annotations),
            )?;
        }
        writeln!(output, "] }},")?;
    }
    writeln!(output, "    ],")
}

fn write_choices(graph: &CompiledGraph, output: &mut dyn Write) -> io::Result<()> {
    writeln!(output, "    choices: &[")?;
    for choice in &graph.choices {
        write!(
            output,
            "    Choice {{ name: {}, arms: &[",
            quote(graph.text(choice.name))
        )?;
        for arm in &graph.arms[index(&choice.arms)] {
            write!(
                output,
                "Arm {{ condition: {}, tag: {}, annotations: {} }}, ",
                option(arm.condition),
                quote(graph.text(arm.tag)),
                annotation_list(graph, &arm.annotations),
            )?;
        }
        writeln!(output, "] }},")?;
    }
    writeln!(output, "    ],")
}

/// A `pub mod <module>` of constants. Each name becomes an upper-case identifier; names that
/// collide after that rewrite are an error, because the constants would overlap.
fn constants<'a>(
    output: &mut dyn Write,
    module: &str,
    ty: &str,
    entries: impl Iterator<Item = (&'a str, String)>,
) -> io::Result<()> {
    writeln!(output, "pub mod {module} {{")?;
    let mut seen = HashSet::new();
    for (name, value) in entries {
        let ident = ident(name);
        if !seen.insert(ident.clone()) {
            return Err(io::Error::new(
                io::ErrorKind::InvalidData,
                format!("two names in `{module}` both become the Rust constant `{ident}`"),
            ));
        }
        writeln!(output, "    pub const {ident}: {ty} = {value};")?;
    }
    writeln!(output, "}}\n")
}

/// Whether a graph name can be a Rust module name as written: an identifier, and not a keyword.
fn is_module_name(name: &str) -> bool {
    const KEYWORDS: &[&str] = &[
        "as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum",
        "extern", "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move",
        "mut", "pub", "ref", "return", "self", "static", "struct", "super", "trait", "true",
        "type", "unsafe", "use", "where", "while",
    ];
    let mut characters = name.chars();
    let starts_well = characters
        .next()
        .is_some_and(|first| first == '_' || first.is_ascii_alphabetic());
    starts_well
        && characters.all(|c| c == '_' || c.is_ascii_alphanumeric())
        && !KEYWORDS.contains(&name)
}

/// The Rust constant for a graph name: upper case, with any character that is not ASCII
/// alphanumeric replaced by `_`, and a leading `_` when the name starts with a digit.
fn ident(name: &str) -> String {
    let mut out = String::with_capacity(name.len() + 1);
    if name.starts_with(|c: char| c.is_ascii_digit()) {
        out.push('_');
    }
    for c in name.chars() {
        out.push(if c.is_ascii_alphanumeric() {
            c.to_ascii_uppercase()
        } else {
            '_'
        });
    }
    out
}

/// A Rust string literal. `Debug` on `str` escapes every character Rust needs escaped.
fn quote(value: &str) -> String {
    format!("{value:?}")
}

/// `Some(value)` or `None`, as Rust source. A `String` argument is written verbatim, so a
/// pre-quoted literal stays a literal.
fn option(value: Option<impl std::fmt::Display>) -> String {
    match value {
        Some(value) => format!("Some({value})"),
        None => "None".into(),
    }
}

fn string_list(graph: &CompiledGraph, ids: &[StringId]) -> String {
    ids.iter()
        .map(|id| quote(graph.text(*id)))
        .collect::<Vec<_>>()
        .join(", ")
}

/// A `&[Annotation { .. }]` slice for the annotations in `span`.
fn annotation_list(graph: &CompiledGraph, span: &Span) -> String {
    let rows: Vec<String> = graph.annotations[index(span)]
        .iter()
        .map(|entry| annotation(graph, entry))
        .collect();
    format!("&[{}]", rows.join(", "))
}

fn annotation(graph: &CompiledGraph, entry: &Annotation) -> String {
    format!(
        "Annotation {{ key: {}, value: {} }}",
        quote(graph.text(entry.key)),
        option(entry.value.map(|value| quote(graph.text(value)))),
    )
}
